# -*- coding: utf-8 -*-
"""first.html 4단계 흐름 빠른 점검 (개발용 프로브)."""
import os, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import verify_multipage as V
from playwright.sync_api import sync_playwright

ROOT = V.ROOT
srv, base = V.start_server()
print('base', base)
with sync_playwright() as p:
    b = V.launch(p)
    ctx = b.new_context(viewport={'width': 1400, 'height': 1000})
    pg = ctx.new_page()
    pg.set_default_timeout(15000)
    w = V.Watcher(pg, base)
    V.goto(pg, base + 'first.html', 900)
    print('problems:', w.problems()[:5])
    print('fcStep', pg.evaluate("() => window.SEOSAN_VERIFY.fcStep()"))
    print('fcMode', pg.evaluate("() => window.SEOSAN_VERIFY.fcMode()"))
    print('fcState', pg.evaluate("() => window.SEOSAN_VERIFY.fcState()"))
    print('fcMax', pg.evaluate("() => window.SEOSAN_VERIFY.fcMax()"))
    print('rows', pg.eval_on_selector_all('#firstList .fc-item', 'e => e.length'))
    print('banner', (pg.text_content('#fcBanner') or '')[:120].replace('\n', ' '))
    print('foot', pg.evaluate("() => window.SEOSAN_VERIFY.fcFoot()"))
    # step1 validation should fail
    print('next1', pg.evaluate("() => window.SEOSAN_VERIFY.fcNext()"))
    print('step after next1', pg.evaluate("() => window.SEOSAN_VERIFY.fcStep()"))
    print('prompt', pg.evaluate("() => window.SEOSAN_VERIFY.guestPromptState()"))
    pg.evaluate("() => window.SEOSAN_VERIFY.guestAccept()")
    print('set', pg.evaluate("() => window.SEOSAN_VERIFY.fcSet({advertiser:'프로브광고주', text:'프로브 문구 검증', file:true, agree:true, license:true, qty:2, picks:'auto'})"))
    print('next2', pg.evaluate("() => window.SEOSAN_VERIFY.fcNext()"))
    print('step', pg.evaluate("() => window.SEOSAN_VERIFY.fcStep()"))
    print('next3', pg.evaluate("() => window.SEOSAN_VERIFY.fcNext()"))
    print('step', pg.evaluate("() => window.SEOSAN_VERIFY.fcStep()"))
    print('summary', (pg.evaluate("() => window.SEOSAN_VERIFY.fcSummary()") or '')[:300].replace('\n', ' '))
    before = pg.evaluate("() => window.SEOSAN_VERIFY.apps().length")
    print('submit', pg.evaluate("() => window.SEOSAN_VERIFY.fcSubmit()"))
    after = pg.evaluate("() => window.SEOSAN_VERIFY.apps().length")
    print('apps', before, '->', after)
    print('modal', (pg.text_content('#modalBody') or '')[:200].replace('\n', ' '))
    print('problems2:', w.problems()[:5])
    pg.evaluate("() => window.SEOSAN_VERIFY.closeModal()")
    # next mode
    print('mode next', pg.evaluate("() => window.SEOSAN_VERIFY.fcSet({mode:'next', daySim:'thu', fcTime:'open', qty:1, picks:[]})"))
    print('banner2', (pg.text_content('#fcBanner') or '')[:160].replace('\n', ' '))
    print('rows2', pg.eval_on_selector_all('#firstList .fc-item', 'e => e.length'), 'btns', pg.eval_on_selector_all('[data-fcpick]:not([disabled])', 'e => e.length'))
    print('nextA', pg.evaluate("() => window.SEOSAN_VERIFY.fcNext()"))
    print('step', pg.evaluate("() => window.SEOSAN_VERIFY.fcStep()"))
    print('nextB', pg.evaluate("() => window.SEOSAN_VERIFY.fcNext()"))
    print('step', pg.evaluate("() => window.SEOSAN_VERIFY.fcStep()"))
    print('submit2', pg.evaluate("() => window.SEOSAN_VERIFY.fcSubmit()"))
    print('due', pg.evaluate("() => { const a = window.SEOSAN_VERIFY.state().apps.slice(-1)[0]; return {id:a.id,status:a.status,due:a.deliveryDue,firstCome:a.firstCome}; }"))
    print('problems3:', w.problems()[:5])
    ctx.close()
    b.close()
srv.shutdown()
